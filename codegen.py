"""
codegen.py - RecipeLang TARGET CODE GENERATION

The compiler's back end. From the (optimized) IR it generates two real,
separate target programs:

  1. <Recipe>.py   - a standalone Python program that prints the cooking
                     instructions (it runs without RecipeLang installed)
  2. <Recipe>.html - a recipe card (ingredients table, steps, total time)

This is the "target code generation" phase of a compiler: the same IR is
translated into different target languages.
"""

import os
import html

TO_SECONDS = {"second": 1, "seconds": 1, "minute": 60, "minutes": 60,
              "hour": 3600, "hours": 3600}


def _amount(arg):
    unit = f" {arg['unit']}" if arg["unit"] else ""
    return f"{arg['quantity']}{unit}"


def describe(instr):
    """Turns one IR instruction into an English sentence."""
    ings = [a for a in instr.resolved_args if a["kind"] == "ingredient"]
    times = [a for a in instr.resolved_args if a["kind"] == "time"]
    act = instr.action
    if act == "heat_pan":
        return "Heat the pan"
    if act == "add" and ings:
        return "Add " + " and ".join(f"{_amount(a)} {a['name']}" for a in ings)
    if act == "cook" and times:
        return f"Cook for {times[0]['duration']} {times[0]['unit']}"
    if act == "stir":
        return "Stir well"
    if act == "serve":
        return "Serve hot"
    if act == "boil" and ings:
        return "Boil " + " and ".join(f"{_amount(a)} {a['name']}" for a in ings)
    parts = [a["name"] if a["kind"] == "ingredient" else f"{a['duration']} {a['unit']}"
             for a in instr.resolved_args]
    return f"{act.replace('_', ' ').capitalize()} {' '.join(parts)}".strip()


def totals(ir):
    used, seconds = {}, 0
    for instr in ir:
        for a in instr.resolved_args:
            if a["kind"] == "ingredient":
                e = used.setdefault(a["name"], [0, a["unit"]])
                e[0] += a["quantity"]
            else:
                seconds += a["duration"] * TO_SECONDS[a["unit"]]
    return used, seconds


def generate_python(name, ir):
    used, seconds = totals(ir)
    lines = [
        f"# Auto-generated by the RecipeLang compiler from recipe '{name}'.",
        "# Do not edit by hand - change the .recipe file and recompile.",
        "",
        f"print('=== {name} ===')",
        "print()",
        "print('Ingredients:')",
    ]
    for nm, (q, u) in used.items():
        lines.append(f"print('  - {q}{(' ' + u) if u else ''} {nm}')")
    lines += ["print()", "print('Method:')"]
    for instr in ir:
        lines.append(f"print('  {instr.index}. {describe(instr)}')")
    lines += ["print()", f"print('Total cooking time: {seconds // 60} minute(s)')"]
    return "\n".join(lines) + "\n"


def generate_html(name, ir):
    used, seconds = totals(ir)
    rows = "".join(
        f"<tr><td>{html.escape(nm)}</td><td>{q}{(' ' + html.escape(u)) if u else ''}</td></tr>"
        for nm, (q, u) in used.items())
    steps = "".join(f"<li>{html.escape(describe(i))}</li>" for i in ir)
    return f"""<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>{html.escape(name)}</title>
<style>
body{{font-family:Arial,sans-serif;max-width:560px;margin:40px auto;padding:0 16px;color:#222}}
h1{{color:#b84a22}} table{{border-collapse:collapse;width:100%}}
td,th{{border-bottom:1px solid #ddd;padding:8px;text-align:left}}
.badge{{background:#17211e;color:#fff;border-radius:12px;padding:4px 12px}}
</style></head><body>
<h1>{html.escape(name)}</h1>
<p><span class="badge">Total cooking time: {seconds // 60} min</span></p>
<h2>Ingredients</h2><table><tr><th>Item</th><th>Amount</th></tr>{rows}</table>
<h2>Method</h2><ol>{steps}</ol>
<p><small>Generated by the RecipeLang compiler.</small></p>
</body></html>
"""


def write_targets(name, ir, out_dir="compiled_output"):
    os.makedirs(out_dir, exist_ok=True)
    py_path = os.path.join(out_dir, f"{name}.py")
    html_path = os.path.join(out_dir, f"{name}.html")
    with open(py_path, "w", encoding="utf-8") as f:
        f.write(generate_python(name, ir))
    with open(html_path, "w", encoding="utf-8") as f:
        f.write(generate_html(name, ir))
    return py_path, html_path
